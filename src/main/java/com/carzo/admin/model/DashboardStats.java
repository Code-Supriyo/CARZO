package com.carzo.admin.model;

public class DashboardStats {

    private long totalAdmins;
    private long totalUsers;
    private long totalCars;
    private long totalCategories;
    private long totalBrands;
    private long totalPurchases;
    private long totalWishlistItems;

    public long getTotalAdmins() {
        return totalAdmins;
    }

    public void setTotalAdmins(long totalAdmins) {
        this.totalAdmins = totalAdmins;
    }

    public long getTotalUsers() {
        return totalUsers;
    }

    public void setTotalUsers(long totalUsers) {
        this.totalUsers = totalUsers;
    }

    public long getTotalCars() {
        return totalCars;
    }

    public void setTotalCars(long totalCars) {
        this.totalCars = totalCars;
    }

    public long getTotalCategories() {
        return totalCategories;
    }

    public void setTotalCategories(long totalCategories) {
        this.totalCategories = totalCategories;
    }

    public long getTotalBrands() {
        return totalBrands;
    }

    public void setTotalBrands(long totalBrands) {
        this.totalBrands = totalBrands;
    }

    public long getTotalPurchases() {
        return totalPurchases;
    }

    public void setTotalPurchases(long totalPurchases) {
        this.totalPurchases = totalPurchases;
    }

    public long getTotalWishlistItems() {
        return totalWishlistItems;
    }

    public void setTotalWishlistItems(long totalWishlistItems) {
        this.totalWishlistItems = totalWishlistItems;
    }
}